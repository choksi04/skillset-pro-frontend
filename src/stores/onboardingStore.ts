export function getTourStepsForRole(role: UserRole): TourStep[] {
  const steps = coreTourSteps.filter((s) => s.roles.includes(role));
  if (role === 'admin' || role === 'hr') return [...steps, ...adminExtraSteps];
  if (role === 'manager' || role === 'domain_lead') return [...steps, ...managerExtraSteps];
  if (role === 'employee') return [...steps, ...employeeExtraSteps];
  return steps;
}

